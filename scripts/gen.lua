-- Generate every file under extras/ and PALETTE.md from lua/kage.
-- Run from the repo root: nvim -l scripts/gen.lua
package.path = "./lua/?.lua;./lua/?/init.lua;" .. package.path

local colors = require("kage.colors")
local palette = require("kage.palette")

local VARIANTS = { "shadow", "dawn" }
local TITLE = { shadow = "kage shadow", dawn = "kage dawn" }

local function write(path, text)
  vim.fn.mkdir(vim.fn.fnamemodify(path, ":h"), "p")
  local f = assert(io.open(path, "w"))
  f:write(text)
  f:close()
  print("wrote " .. path)
end

local function hex(s)
  return (s:gsub("#", ""))
end

local function header(comment, variant)
  return comment .. " " .. TITLE[variant] .. ", generated by kage-theme (scripts/gen.lua). Do not edit.\n"
end

-- terminal emulators ----------------------------------------------------------

local function foot_section(c, name)
  local t = c.terminal
  local lines = {
    "[" .. name .. "]",
    "background=" .. hex(c.bg),
    "foreground=" .. hex(c.fg),
    "cursor=" .. hex(c.bg) .. " " .. hex(c.lantern),
    "flash=" .. hex(c.lantern),
    "",
  }
  for i = 0, 7 do
    lines[#lines + 1] = "regular" .. i .. "=" .. hex(t[i + 1])
  end
  lines[#lines + 1] = ""
  for i = 0, 7 do
    lines[#lines + 1] = "bright" .. i .. "=" .. hex(t[i + 9])
  end
  vim.list_extend(lines, {
    "",
    "16=" .. hex(c.orange),
    "17=" .. hex(c.red),
    "",
    "selection-foreground=" .. hex(c.fg_strong),
    "selection-background=" .. hex(c.bg_visual),
    "urls=" .. hex(c.blue),
    "jump-labels=" .. hex(c.bg) .. " " .. hex(c.lantern),
    "scrollback-indicator=" .. hex(c.bg) .. " " .. hex(c.lantern),
    "search-box-match=" .. hex(c.bg) .. " " .. hex(c.lantern),
    "search-box-no-match=" .. hex(c.bg) .. " " .. hex(c.red),
  })
  return table.concat(lines, "\n") .. "\n"
end

-- foot 1.28 only takes [colors-dark] and [colors-light]; a dawn-only file
-- also starts foot in its light theme.
local function foot(c, v)
  if v == "dawn" then
    return header("#", v) .. "[main]\ninitial-color-theme=light\n\n" .. foot_section(c, "colors-light")
  end
  return header("#", v) .. foot_section(c, "colors-dark")
end

local function ghostty(c, v)
  local out = { header("#", v) }
  for i, color in ipairs(c.terminal) do
    out[#out + 1] = "palette = " .. (i - 1) .. "=" .. color .. "\n"
  end
  vim.list_extend(out, {
    "background = " .. c.bg .. "\n",
    "foreground = " .. c.fg .. "\n",
    "cursor-color = " .. c.lantern .. "\n",
    "cursor-text = " .. c.bg .. "\n",
    "selection-background = " .. c.bg_visual .. "\n",
    "selection-foreground = " .. c.fg_strong .. "\n",
  })
  return table.concat(out)
end

local function kitty(c, v)
  local out = { header("#", v) }
  vim.list_extend(out, {
    "background " .. c.bg .. "\n",
    "foreground " .. c.fg .. "\n",
    "cursor " .. c.lantern .. "\n",
    "cursor_text_color " .. c.bg .. "\n",
    "selection_background " .. c.bg_visual .. "\n",
    "selection_foreground " .. c.fg_strong .. "\n",
    "url_color " .. c.blue .. "\n",
    "active_border_color " .. c.lantern .. "\n",
    "inactive_border_color " .. c.border .. "\n",
    "active_tab_background " .. c.bg .. "\n",
    "active_tab_foreground " .. c.fg_strong .. "\n",
    "inactive_tab_background " .. c.bg_dark .. "\n",
    "inactive_tab_foreground " .. c.fg_dark .. "\n",
    "tab_bar_background " .. c.bg_dark .. "\n",
  })
  for i, color in ipairs(c.terminal) do
    out[#out + 1] = "color" .. (i - 1) .. " " .. color .. "\n"
  end
  return table.concat(out)
end

local function alacritty(c, v)
  local t = c.terminal
  local names = { "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white" }
  local out = { header("#", v) }
  out[#out + 1] = '[colors.primary]\nbackground = "' .. c.bg .. '"\nforeground = "' .. c.fg .. '"\n\n'
  out[#out + 1] = '[colors.cursor]\ncursor = "' .. c.lantern .. '"\ntext = "' .. c.bg .. '"\n\n'
  out[#out + 1] = '[colors.selection]\nbackground = "' .. c.bg_visual .. '"\ntext = "' .. c.fg_strong .. '"\n\n'
  out[#out + 1] = "[colors.normal]\n"
  for i, n in ipairs(names) do
    out[#out + 1] = n .. ' = "' .. t[i] .. '"\n'
  end
  out[#out + 1] = "\n[colors.bright]\n"
  for i, n in ipairs(names) do
    out[#out + 1] = n .. ' = "' .. t[i + 8] .. '"\n'
  end
  return table.concat(out)
end

local function wezterm(c, v)
  local function list(from)
    local items = {}
    for i = from, from + 7 do
      items[#items + 1] = '"' .. c.terminal[i] .. '"'
    end
    return "[" .. table.concat(items, ", ") .. "]"
  end
  return header("#", v)
    .. "[colors]\n"
    .. 'background = "'
    .. c.bg
    .. '"\n'
    .. 'foreground = "'
    .. c.fg
    .. '"\n'
    .. 'cursor_bg = "'
    .. c.lantern
    .. '"\n'
    .. 'cursor_fg = "'
    .. c.bg
    .. '"\n'
    .. 'cursor_border = "'
    .. c.lantern
    .. '"\n'
    .. 'selection_bg = "'
    .. c.bg_visual
    .. '"\n'
    .. 'selection_fg = "'
    .. c.fg_strong
    .. '"\n'
    .. 'split = "'
    .. c.border
    .. '"\n'
    .. "ansi = "
    .. list(1)
    .. "\n"
    .. "brights = "
    .. list(9)
    .. "\n"
    .. 'scrollbar_thumb = "'
    .. c.bg_raised
    .. '"\n\n'
    .. "[colors.indexed]\n"
    .. '16 = "'
    .. c.orange
    .. '"\n'
    .. '17 = "'
    .. c.red
    .. '"\n\n'
    .. "[colors.tab_bar]\n"
    .. 'background = "'
    .. c.bg_dark
    .. '"\n\n'
    .. "[colors.tab_bar.active_tab]\n"
    .. 'bg_color = "'
    .. c.lantern
    .. '"\nfg_color = "'
    .. c.bg_dark
    .. '"\n\n'
    .. "[colors.tab_bar.inactive_tab]\n"
    .. 'bg_color = "'
    .. c.bg_dark
    .. '"\nfg_color = "'
    .. c.comment
    .. '"\n\n'
    .. "[colors.tab_bar.inactive_tab_hover]\n"
    .. 'bg_color = "'
    .. c.bg_raised
    .. '"\nfg_color = "'
    .. c.fg
    .. '"\n\n'
    .. "[colors.tab_bar.new_tab]\n"
    .. 'bg_color = "'
    .. c.bg_dark
    .. '"\nfg_color = "'
    .. c.comment
    .. '"\n\n'
    .. "[colors.tab_bar.new_tab_hover]\n"
    .. 'bg_color = "'
    .. c.bg_raised
    .. '"\nfg_color = "'
    .. c.fg
    .. '"\n\n'
    .. "[metadata]\n"
    .. 'name = "'
    .. TITLE[v]
    .. '"\n'
end

local function fzf(c, v)
  local pairs_ = {
    { "bg", c.bg },
    { "bg+", c.bg_raised },
    { "fg", c.fg },
    { "fg+", c.fg_strong },
    { "hl", c.lantern },
    { "hl+", c.lantern },
    { "info", c.comment },
    { "prompt", c.purple },
    { "pointer", c.lantern },
    { "marker", c.pink },
    { "spinner", c.purple },
    { "header", c.fg_dark },
    { "border", c.border },
    { "gutter", c.bg },
    { "query", c.fg_strong },
  }
  local parts = {}
  for _, p in ipairs(pairs_) do
    parts[#parts + 1] = p[1] .. ":" .. p[2]
  end
  return header("#", v) .. 'export FZF_DEFAULT_OPTS="$FZF_DEFAULT_OPTS --color=' .. table.concat(parts, ",") .. '"\n'
end

