local function palette_md(all_c)
  local s, d = all_c.shadow, all_c.dawn
  local out = {
    "# kage palette\n\n",
    "Generated by `nvim -l scripts/gen.lua` from `lua/kage/palette.lua`. Do not edit by hand.\n\n",
    "Two variants: **kage shadow** (dark) and **kage dawn** (light). Copy any value into another app; ",
    "ready-made configs for foot, ghostty, kitty, alacritty, wezterm, fzf, the kage TUI and CSS are under `extras/`.\n\n",
    "## Base tokens\n\n| token | shadow | dawn | used for |\n|---|---|---|---|\n",
  }
  for _, k in ipairs(TOKEN_KEYS) do
    out[#out + 1] = ("| `%s` | `%s` | `%s` | %s |\n"):format(k, s[k], d[k], USE[k] or "")
  end
  out[#out + 1] = "\n## Derived tokens\n\n| token | shadow | dawn |\n|---|---|---|\n"
  for _, k in ipairs({ "add", "delete", "change", "text" }) do
    out[#out + 1] = ("| `diff.%s` | `%s` | `%s` |\n"):format(k, s.diff[k], d.diff[k])
  end
  for _, k in ipairs({ "error", "warning", "info", "hint" }) do
    out[#out + 1] = ("| `diag_bg.%s` | `%s` | `%s` |\n"):format(k, s.diag_bg[k], d.diag_bg[k])
  end
  out[#out + 1] = "\n## Terminal colors (ANSI 0 to 15)\n\n| index | name | shadow | dawn |\n|---|---|---|---|\n"
  local names = { "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white" }
  for i = 1, 16 do
    local n = (i > 8 and "bright " or "") .. names[(i - 1) % 8 + 1]
    out[#out + 1] = ("| %d | %s | `%s` | `%s` |\n"):format(i - 1, n, s.terminal[i], d.terminal[i])
  end
  out[#out + 1] = "\nExtra indexes used by foot: 16 is `orange`, 17 is `red`. Cursor is `orange` on `bg`; "
  out[#out + 1] = "selection is `bg_visual` with `fg_strong` text.\n"
  out[#out + 1] = "\n## Syntax roles\n\n| role | token |\n|---|---|\n"
  for _, r in ipairs({
    { "comments", "comment (italic)" },
    { "keywords, conditionals, imports", "purple" },
    { "functions, methods", "blue" },
    { "builtin functions", "cyan" },
    { "strings", "green" },
    { "escapes, regex specials", "pink / cyan" },
    { "numbers, booleans, constants", "orange" },
    { "types, constructors", "yellow" },
    { "builtin types", "yellow (italic)" },
    { "variables", "fg" },
    { "self, this", "pink (italic)" },
    { "parameters", "sand" },
    { "properties, fields", "mist" },
    { "modules, namespaces, labels", "cyan" },
    { "macros, attributes, decorators", "pink" },
    { "operators", "operator" },
    { "punctuation", "punct" },
    { "markup headings 1 to 6", "orange, purple, blue, cyan, green, yellow" },
  }) do
    out[#out + 1] = ("| %s | `%s` |\n"):format(r[1], r[2])
  end
  return table.concat(out)
end

-- run ----------------------------------------------------------------------------

local all_c, all_flat = {}, {}
for _, v in ipairs(VARIANTS) do
  local c = colors.get(v)
  all_c[v] = c
  all_flat[v] = flat(c)
  local base = "extras/"
  write(base .. "foot/kage-" .. v .. ".ini", foot(c, v))
  write(base .. "ghostty/kage-" .. v, ghostty(c, v))
  write(base .. "kitty/kage-" .. v .. ".conf", kitty(c, v))
  write(base .. "alacritty/kage-" .. v .. ".toml", alacritty(c, v))
  write(base .. "wezterm/kage-" .. v .. ".toml", wezterm(c, v))
  write(base .. "fzf/kage-" .. v .. ".sh", fzf(c, v))
  write(base .. "kage/kage-" .. v .. ".toml", kage_tui(c, v))
end

write(
  "extras/foot/kage.ini",
  "# kage for foot: shadow as [colors-dark], dawn as [colors-light]. Generated by scripts/gen.lua.\n"
    .. foot_section(all_c.shadow, "colors-dark")
    .. "\n"
    .. foot_section(all_c.dawn, "colors-light")
)
write("extras/css/kage.css", css(all_flat))
write("extras/json/kage.json", json({ shadow = all_flat.shadow, dawn = all_flat.dawn, base = palette }) .. "\n")
write("PALETTE.md", palette_md(all_c))
