local TOKEN_KEYS = {
  "bg",
  "bg_dark",
  "bg_float",
  "bg_highlight",
  "bg_raised",
  "bg_visual",
  "bg_search",
  "fg",
  "fg_strong",
  "fg_dark",
  "comment",
  "fg_gutter",
  "border",
  "orange",
  "purple",
  "magenta",
  "green",
  "yellow",
  "red",
  "blue",
  "cyan",
  "teal",
  "pink",
  "mist",
  "sand",
  "operator",
  "punct",
}

local function flat(c)
  local t = {}
  for _, k in ipairs(TOKEN_KEYS) do
    t[k] = c[k]
  end
  for k, val in pairs(c.diff) do
    t["diff_" .. k] = val
  end
  for k, val in pairs(c.diag_bg) do
    t["diag_bg_" .. k] = val
  end
  for i, val in ipairs(c.terminal) do
    t["ansi_" .. (i - 1)] = val
  end
  return t
end

local function sorted_keys(t)
  local keys = vim.tbl_keys(t)
  table.sort(keys, function(a, b)
    local na, nb = a:match("^ansi_(%d+)$"), b:match("^ansi_(%d+)$")
    if na and nb then
      return tonumber(na) < tonumber(nb)
    end
    return a < b
  end)
  return keys
end

local function css(all)
  local out = { "/* kage shadow and kage dawn, generated by kage-theme (scripts/gen.lua). Do not edit. */\n" }
  local function block(sel, t)
    out[#out + 1] = sel .. " {\n"
    for _, k in ipairs(sorted_keys(t)) do
      out[#out + 1] = "  --kage-" .. k:gsub("_", "-") .. ": " .. t[k] .. ";\n"
    end
    out[#out + 1] = "}\n"
  end
  block(':root,\n[data-theme="kage-shadow"]', all.shadow)
  block('[data-theme="kage-dawn"]', all.dawn)
  out[#out + 1] = "@media (prefers-color-scheme: light) {\n  :root:not([data-theme]) {\n"
  for _, k in ipairs(sorted_keys(all.dawn)) do
    out[#out + 1] = "    --kage-" .. k:gsub("_", "-") .. ": " .. all.dawn[k] .. ";\n"
  end
  out[#out + 1] = "  }\n}\n"
  return table.concat(out)
end

-- JSON with sorted keys, so the output is byte-stable between runs
local function json(value, indent)
  indent = indent or ""
  if type(value) ~= "table" then
    return vim.json.encode(value)
  end
  local inner = indent .. "  "
  local parts = {}
  for _, k in ipairs(sorted_keys(value)) do
    parts[#parts + 1] = inner .. vim.json.encode(k) .. ": " .. json(value[k], inner)
  end
  return "{\n" .. table.concat(parts, ",\n") .. "\n" .. indent .. "}"
end

